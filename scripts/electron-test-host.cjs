const { app, BrowserWindow, session } = require('electron')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
app.setPath('userData', join(process.env.BOOTH_TEST_DIR, 'profile'))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1440, height: 920, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_details, callback) => callback({ cancel: true }))
  await win.loadURL('data:text/html,<html><body><div id="root"></div></body></html>')
  await win.webContents.insertCSS(readFileSync(process.env.BOOTH_TEST_CSS, 'utf8'))
  await win.webContents.executeJavaScript(readFileSync(join(process.env.BOOTH_TEST_DIR, 'renderer.js'), 'utf8'))
  const result = await win.webContents.executeJavaScript('window.runRegression()')
  console.log(JSON.stringify(result))
  app.exit(0)
}).catch((error) => { console.error(error); app.exit(1) })
